// =========================================================================
// semester.js —— 学期推荐日期（纯算法，不依赖数据库）
//
// 为什么单独成模块：这份「按当前月份分档推学期名与起止日期」的规则有两个调用方 ——
//   1. 设置页「增加学期」与课表路由（routes/schedule.js）；
//   2. 首次引导页（此时账号还没建、库也不存在，走 routes 里的实现会直接撞上未打开 db）。
// 抄成两份的话，改了一处（比如 7 月改 9 月）另一处会静默停在旧规则，
// 表现为「设置页推荐的学期和引导页不一样」，且两边都看不出哪里错了。
// =========================================================================

function autoSemester() {
  const y = new Date().getFullYear();
  const m = new Date().getMonth() + 1;
  if (m >= 7) return { name: `${y}秋季学期`, start_date: `${y}-09-01`, end_date: `${y + 1}-01-31` };
  if (m === 1) return { name: `${y - 1}秋季学期`, start_date: `${y - 1}-09-01`, end_date: `${y}-01-31` };
  return { name: `${y}夏季学期`, start_date: `${y}-02-01`, end_date: `${y}-06-30` };
}

module.exports = { autoSemester };
