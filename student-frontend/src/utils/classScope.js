// =========================================================================
// classScope.js —— 「当前操作的是哪个班级库」的渲染代次
//
// 为什么单独有一个文件：
//   切班不是换用户（token 里的身份不变，变的只是 dbSlug），所以不能走登出流程；
//   但它换的是**一整套物理数据**（学生/座位/班费/相册全在另一个 .db 文件里）。
//   对前端来说，切班后此前加载过的每一个视图实例都成了「上一个班的数据」。
//
//   业务页面全被 <KeepAlive :max="16"> 缓存着（见 App.vue），组件不会 unmount，
//   onMounted 里的拉数据逻辑因此不会重跑 —— 这就是原实现只能 window.location.reload()
//   的原因。reload 当然对，但代价是整页白屏重来、丢掉当前滚动位置与路由，
//   用户只是想换个班看一眼。
//
//   这里给 KeepAlive 一个 key：递增它就等于「把所有缓存的视图实例全部作废」，
//   当前路由页会重新 mount、重新拉该班的数据，而不需要重载整个渲染进程。
//
// 与 userScopedCache.js 的分工：
//   · userScopedCache：清理**模块级**缓存（仪表盘数据、学期起点、照片信息…），
//     并让在途请求的响应作废。它管的是「不在组件里的状态」。
//   · classScope：作废**组件实例**（KeepAlive 里的那一堆 ref）。两者互补，切班要一起调。
//
// 为什么不把两者合二为一：
//   登出要清模块缓存，但那时路由会跳去 /login，KeepAlive 里的实例自然被丢弃，
//   不需要动 key；切班则相反，路由不变、必须主动作废实例。合并会让「为什么这里要
//   作废实例」变成一句说不清的话，出问题也不好定位是哪一半失效了。
// =========================================================================
import { ref } from 'vue'

// 每次切班（含新建班级后自动进入）+1。App.vue 拿它当 KeepAlive 的 key。
export const classScopeKey = ref(0)

/**
 * 作废全部缓存的视图实例，让当前路由重新挂载。
 *
 * 调用方必须在**切班请求已经成功、新 token 已落盘之后**调用：重新挂载的动作
 * 会立刻触发一批数据请求，那些请求带的是新 token 才能读到新班。
 * 提前调用的后果是页面用旧 token 拉了一遍新班的数据，全部 404 或读到旧班。
 */
export function bumpClassScope() {
  classScopeKey.value += 1
}

/**
 * 「班级信息设置」弹窗是否打开（跨视图重建保留）。
 *
 * 为什么需要它：切班 / 新建班级都会 bumpClassScope，整个视图树连同弹窗一起被销毁。
 * 但用户把这个弹窗当班级切换器用 —— 连续切几个班、或者建完班接着改名字，
 * 每切一次就被关掉很打断。这里用一个模块级状态记住「重建前是开着的」，
 * 新实例挂载后原地恢复。
 *
 * 只在「重建恢复」这条路径上读；用户主动关闭时由 DashboardView 的 watch 写回 false，
 * 所以关掉之后切班不会再弹出来。
 */
export const classDialogOpen = ref(false)

/**
 * 设置页那份班级弹窗的显隐（与首页同一个组件，但各自记自己的）。
 *
 * 为什么不共用 classDialogOpen：两个入口可以同时存在于不同视图，共用一份状态会互相
 * 覆盖 —— 在设置页关闭弹窗时，首页那份的「是否开着」也被改掉了，切班回去就会莫名弹出来。
 */
export const settingsClassDialogOpen = ref(false)
